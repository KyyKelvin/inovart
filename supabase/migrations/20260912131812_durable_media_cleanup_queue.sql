create or replace function public.read_media_cleanup(p_limit integer default 100)
returns table(id bigint, object_path text)
language plpgsql
security invoker
set search_path=''
as $$
begin
  if coalesce(auth.jwt()->>'role','') <> 'service_role' then
    raise exception 'Forbidden';
  end if;
  if p_limit not between 1 and 100 then
    raise exception 'Invalid limit';
  end if;
  return query
    select q.id, q.object_path
    from private.media_cleanup_queue q
    order by q.attempts, q.created_at
    limit p_limit;
end
$$;
revoke all on function public.read_media_cleanup(integer) from public, anon, authenticated;
grant execute on function public.read_media_cleanup(integer) to service_role;

create or replace function public.finish_media_cleanup(p_ids bigint[], p_error text default null)
returns integer
language plpgsql
security invoker
set search_path=''
as $$
declare changed integer;
begin
  if coalesce(auth.jwt()->>'role','') <> 'service_role' then
    raise exception 'Forbidden';
  end if;
  if p_ids is null or cardinality(p_ids) not between 1 and 100 then
    raise exception 'Invalid identifiers';
  end if;
  if p_error is null then
    delete from private.media_cleanup_queue where id = any(p_ids);
  else
    update private.media_cleanup_queue
    set attempts = attempts + 1,
        last_error = left(p_error, 500),
        updated_at = now()
    where id = any(p_ids);
  end if;
  get diagnostics changed = row_count;
  return changed;
end
$$;
revoke all on function public.finish_media_cleanup(bigint[],text) from public, anon, authenticated;
grant execute on function public.finish_media_cleanup(bigint[],text) to service_role;
